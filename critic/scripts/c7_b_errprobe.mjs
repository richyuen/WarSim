// Critic run 7: when does "n is not a function" start? Records errors (with stack) after each step.
import { launch, BASE, shot, save, lookAt, CELLS, maxSpeed, run, pause } from './c7_lib.mjs';

const seed = Number(process.argv[2] ?? 5527);
const { browser, page } = await launch();
const errs = [];
page.on('pageerror', (e) => errs.push({ at: step, msg: e.message, stack: (e.stack ?? '').slice(0, 900) }));
let step = 'boot';
const log = [];
const mark = (s) => { log.push({ step, errors: errs.length }); step = s; };
await page.goto(`${BASE}/?scenario=1938&paused=1&seed=${seed}`);
await page.waitForFunction(() => (window.__warsim?.view?.frames ?? 0) > 0, null, { timeout: 180_000 });
await page.waitForTimeout(3000);
mark('lookAt');
const [bx, by] = CELLS.berlin;
await lookAt(page, bx, by, 2500);
mark('hover');
await page.mouse.move(800, 450);
await page.waitForTimeout(1500);
mark('click');
await page.mouse.click(800, 450);
await page.waitForTimeout(1500);
mark('escape');
await page.keyboard.press('Escape');
await page.waitForTimeout(800);
mark('key2');
await page.keyboard.press('2');
await page.waitForTimeout(1500);
mark('key9');
await page.keyboard.press('9');
await page.waitForTimeout(1500);
mark('key1');
await page.keyboard.press('1');
await page.waitForTimeout(1000);
mark('mouseaway');
await page.mouse.move(5, 500);
await page.waitForTimeout(1000);
mark('run30s');
await maxSpeed(page);
await run(page);
await page.waitForTimeout(30000);
mark('pause');
await pause(page);
await page.waitForTimeout(1000);
mark('end');
await shot(page, `c7b_${seed}_end.png`);
save(`c7_b_${seed}.json`, { log, n: errs.length, first: errs.slice(0, 3), distinctStacks: [...new Set(errs.map((e) => e.stack))].slice(0, 5) });
await browser.close();
